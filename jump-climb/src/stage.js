// stage.js — ステージの内容(障害物の配置)。ここの数字を直すだけで、ステージを変えられる。
//
// 障害物(ブロック)の書き方:
//   side: 'L' = 左の境界線から張り出す / 'R' = 右の境界線から張り出す
//   y   : ブロックの下の面の高さ(地面からのpx。上が +)
//   w   : 横幅(px)   h: 厚さ(px)
//   side を書かずに x(画面の左端からの位置)を書くと、空中に浮いたブロックになる。
//
// 当たりのルール(sim.js):
//   上昇中だけ当たる。下から当たると頭をぶつけて落ち始め、横から当たると横の動きが止まる。
//   落下中は通り抜ける(上には乗れない)。落ちるのは時間のロスだけ、という考え方。
//
// 遊べる幅は 300px(境界線の内側)、キャラの幅は 32px。
// 横幅 w は 250 以下にすること(通り抜けられる隙間がなくなるため)。テストでも確認している。
//
// 考え方: 真上に跳び続けるとぶつかる位置にブロックを置き、斜めジャンプでよけさせる。
//   左のブロック(幅150)なら、キャラの中心が x=200 より右にいれば通れる。

export const OBSTACLES = [
  { side: 'L', y: 450,  w: 150, h: 28 },
  { side: 'R', y: 830,  w: 160, h: 28 },
  { side: 'L', y: 1210, w: 170, h: 28 },
  { side: 'R', y: 1590, w: 180, h: 28 },
  { side: 'L', y: 1970, w: 190, h: 28 },
  { side: 'R', y: 2350, w: 190, h: 28 },
  { side: 'L', y: 2730, w: 190, h: 28 },
  { side: 'R', y: 3110, w: 190, h: 28 },
  { side: 'L', y: 3490, w: 190, h: 28 },
  { side: 'R', y: 3870, w: 190, h: 28 },
];

// 境界線の位置(lineL, lineR)に合わせて、実際の座標(x, y, w, h)に直す。
export function buildObstacles(lineL, lineR) {
  return OBSTACLES.map((o) => {
    const x = o.side === 'L' ? lineL : o.side === 'R' ? lineR - o.w : o.x;
    return { x, y: o.y, w: o.w, h: o.h };
  });
}
